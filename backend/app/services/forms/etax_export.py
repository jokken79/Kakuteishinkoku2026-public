def _money(parent: ET.Element, tag: str, value: int) -> None:
    """Emite un tag de monto entero (kingaku) SIN separadores de miles.

    Args:
        parent: Elemento padre donde se añade el tag.
        tag: Nombre del tag oficial (ABA/ABB).
        value: Monto entero en JPY (se serializa sin comas).
    """
    ET.SubElement(parent, tag).text = str(int(value))


def _build_body(parent: ET.Element, draft: FilingDraftResult) -> None:
    """Construye el cuerpo ABB00000 (申告内容第一表) con 収入/所得/控除/税額.

    Reglas de poblado:
        - Solo se emiten los montos con valor (``!= 0``) salvo los totales
          estructurales (合計所得 ⑫, 所得控除合計 ㉚, 課税所得 ㉛) que el 第一表
          siempre lleva. El 事業所得 (ABB00300) se emite aunque sea negativo
          (赤字 con 損益通算).
        - El 申告納税額 (ABB00720) es negativo ⇒ 還付; se emite además el 還付額
          positivo en ABB00760.

    Args:
        parent: Elemento ``KOA020-1`` donde cuelga el cuerpo.
        draft: Resultado del ensamblado del 確定申告.
    """
    tax = draft.tax
    db = tax.deduction_breakdown
    body = ET.SubElement(parent, s.BODY_GROUP)

    # --- 収入金額等 ---
    # 給与収入 (ABB00080): el bruto del 給与 está en el draft solo vía cálculo;
    # se reconstruye desde el 給与所得 no es trivial, así que tomamos el 収入 de
    # la fuente 給与 si está. El draft no expone el 給与収入 bruto directamente,
    # por eso solo emitimos 事業収入 (ABB00030) que sí tenemos (sales_revenue).
    if draft.sales_revenue:
        _money(body, s.TAG_REVENUE_JIGYO, draft.sales_revenue)
    kyuyo_revenue = _kyuyo_gross_from_breakdown(draft)
    if kyuyo_revenue:
        _money(body, s.TAG_REVENUE_KYUYO, kyuyo_revenue)

    # --- 所得金額等 ---
    # 事業所得 (ABB00300): se emite aunque sea negativo (赤字 → 損益通算).
    if draft.business_income != 0:
        _money(body, s.TAG_INCOME_JIGYO, draft.business_income)
    kyuyo_income = _income_by_kind(tax, "kyuyo")
    if kyuyo_income:
        _money(body, s.TAG_INCOME_KYUYO, kyuyo_income)
    # 合計所得金額 ⑫ (estructural, siempre).
    _money(body, s.TAG_INCOME_TOTAL, tax.total_income)

    # --- 所得控除 (solo las con valor) ---
    if db.social_insurance:
        _money(body, s.TAG_DED_SHAKAI, db.social_insurance)
    if db.ideco:
        _money(body, s.TAG_DED_IDECO, db.ideco)
    if db.life_insurance:
        _money(body, s.TAG_DED_LIFE, db.life_insurance)
    if db.earthquake_insurance:
        _money(body, s.TAG_DED_EARTHQUAKE, db.earthquake_insurance)
    if db.medical:
        _money(body, s.TAG_DED_MEDICAL, db.medical)
    if db.furusato:
        _money(body, s.TAG_DED_FURUSATO, db.furusato)
    if db.spouse:
        _money(body, s.TAG_DED_SPOUSE, db.spouse)
    if db.dependents:
        _money(body, s.TAG_DED_DEPENDENTS, db.dependents)
    # 基礎控除 ㉔ (estructural, siempre presente en R7).
    _money(body, s.TAG_DED_KISO, db.kiso)
    # Solo el caso inequívoco de discapacidad ordinaria del titular: `other`
    # puede mezclar otras categorías y no permite separarlas con seguridad.
    if db.ordinary_disability_self and db.other == 270_000:
        _money(body, s.TAG_DED_STUDENT_DISABILITY, 270_000)
    # 所得控除合計 ㉚ (estructural, siempre).
    _money(body, s.TAG_DED_TOTAL, tax.total_income_deductions)

    # --- 税額計算 ---
    # 課税される所得金額 ㉛ (千円未満切捨て — ya redondeado por `calculate`).
    _money(body, s.TAG_TAXABLE_INCOME, tax.taxable_income)
    if tax.income_tax_base:
        _money(body, s.TAG_TAX_BASE, tax.income_tax_base)
    # 住宅借入金等特別控除 ㊱ (百円未満切捨て). El draft inyecta el 住宅ローン控除
    # como `tax_credits`; lo emitimos truncado a ¥100 conforme al esquema.
    if tax.tax_credits:
        _money(body, s.TAG_HOUSING_LOAN, _floor_100(tax.tax_credits))
    # 再差引所得税額 (基準所得税額) ㊹ y 復興特別所得税額 ㊺ → 所得税等の額 ㊻.
    if tax.income_tax_after_credits:
        _money(body, s.TAG_TAX_AFTER_CREDITS, tax.income_tax_after_credits)
    if tax.reconstruction_tax:
        _money(body, s.TAG_RECONSTRUCTION, tax.reconstruction_tax)
    if tax.total_tax:
        _money(body, s.TAG_TAX_TOTAL, tax.total_tax)
    if tax.withholding_tax:
        _money(body, s.TAG_WITHHOLDING, tax.withholding_tax)
    if tax.estimated_prepayment:
        _money(body, s.TAG_PREPAYMENT, tax.estimated_prepayment)
    # 青色申告特別控除額 (59) — solo 青色.
    if draft.filing_type != "shiroiro" and draft.aoiro_deduction:
        _money(body, s.TAG_AOIRO_DEDUCTION, draft.aoiro_deduction)

    # 申告納税額 ㊿ (百円未満切捨て; positivo = 納付, negativo = 還付).
    declared_tax = tax.total_tax - tax.withholding_tax
    _money(body, s.TAG_NOZEI_GAKU, _floor_100(declared_tax) if declared_tax > 0 else declared_tax)
    if tax.final_amount < 0:
        _money(body, s.TAG_REFUND, -tax.final_amount)
    elif tax.final_amount > 0:
        _money(body, s.TAG_PAYMENT, _floor_100(tax.final_amount))


def _floor_100(value: int) -> int:
    """Trunca a la baja al múltiplo de ¥100 (百円未満切捨て), preservando el signo.

    Args:
        value: Monto entero en JPY.

    Returns:
        El monto truncado a ¥100 hacia cero (los importes del 申告書 son ≥0 en
        las casillas que aplican este redondeo).
    """
    return (abs(value) // 100) * 100 * (1 if value >= 0 else -1)


def _income_by_kind(tax: object, kind: str) -> int:
    """Devuelve el 所得金額 de un tipo (``kyuyo``/``jigyo``…) del breakdown.

    Args:
        tax: ``TaxCalculationResult`` (con ``income_breakdown``).
        kind: Valor del ``IncomeKind`` buscado (ej. ``"kyuyo"``).

    Returns:
        El 所得金額 del tipo, o 0 si no aparece.
    """
    return sum(
        cast(int, item.amount)
        for item in getattr(tax, "income_breakdown", [])
        if str(getattr(item.kind, "value", item.kind)) == kind
    )


def _kyuyo_gross_from_breakdown(draft: FilingDraftResult) -> int:
    """Devuelve el salario bruto registrado, sin invertir la deducción salarial."""
    return draft.salary_revenue


def build_xtx(
    draft: FilingDraftResult,
    *,
    identity: XtxIdentity | None = None,
    created_on: date | None = None,
    details: XtxDetails | None = None,
) -> bytes:
    """Construye el borrador XML oficial R7; su descarga exige validación adicional.

    La identidad debe recibirse explícitamente. Nunca se inventa un identificador
    ni se utiliza el マイナンバー enmascarado del perfil. Para obtener los bloques
    pendientes antes de presentar, usar ``build_xtx_document``.
    """
    from app.services.forms.xtx_document import build_xtx_document

    if identity is None:
        raise ValueError("XTX requiere una identidad de e-Tax explícita y transitoria.")
    return build_xtx_document(
        draft,
        identity,
        created_on=created_on or date.today(),
        details=details,
    ).xml


def build_kessansho_csv(draft: FilingDraftResult) -> bytes:
    """Genera el CSV (SHIFT-JIS) del 決算書 (損益計算書 + 貸借対照表).

    El CSV sigue el espiritu del CSV入力規則 del NTA (filas seccion/clave/valor).
    Encoding SHIFT-JIS (exigido por e-Tax para 財務諸表). Caracteres fuera del
    repertorio SHIFT-JIS se reemplazan (replace) para no romper la exportacion.

    Args:
        draft: Resultado del ensamblado.

    Returns:
        Bytes del CSV en SHIFT-JIS.
    """
    pl = draft.income_statement
    bs = draft.balance_sheet

    text_buf = io.StringIO()
    writer = csv.writer(text_buf, lineterminator="\r\n")  # CRLF como e-Tax.

    writer.writerow(["セクション", "科目", "金額"])
    writer.writerow(["決算書", "年度", str(draft.year)])
    writer.writerow(["決算書", "申告区分", draft.filing_type])

    # 損益計算書.
    writer.writerow(["損益計算書", "売上(収入)金額", pl.total_revenue])
    for line in pl.expenses:
        writer.writerow(["損益計算書(経費)", line.account_name, line.amount])
    writer.writerow(["損益計算書", "経費合計", pl.total_expense])
    writer.writerow(["損益計算書", "差引金額(所得金額)", pl.net_income])
    writer.writerow(["損益計算書", "青色申告特別控除額", draft.aoiro_deduction])
    writer.writerow(["損益計算書", "所得金額", draft.business_income])

    # 貸借対照表.
    for bsline in bs.assets:
        writer.writerow(["貸借対照表(資産)", bsline.account_name, bsline.amount])
    writer.writerow(["貸借対照表", "資産合計", bs.total_assets])
    for bsline in bs.liabilities:
        writer.writerow(["貸借対照表(負債)", bsline.account_name, bsline.amount])
    for bsline in bs.equity:
        writer.writerow(["貸借対照表(資本)", bsline.account_name, bsline.amount])
    writer.writerow(["貸借対照表", "当期所得金額", bs.net_income])

    return text_buf.getvalue().encode(CSV_ENCODING, errors="replace")
